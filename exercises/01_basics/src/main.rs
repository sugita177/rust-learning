fn main() {
    // ==========================================
    // 1. 不変性(let)と可変性(let mut)
    // ==========================================
    println!("\n--- 1. 不変性(let)と可変性(let mut) ---");
    // x という名前を 5 という値に束縛する（デフォルトは不変）。
    let x = 5;

    // xは不変のため、変更できない。
    // 以下のように変更しようとすると、コンパイルエラーを生じる。
    // error[E0384]: cannot assign twice to immutable variable `x`
    // x = 6;

    println!("x = {}, xのアドレス: {:p}", x, &x);

    // yを可変として束縛する(mut)。
    let mut y = 5;
    println!("y = {}, yのアドレス: {:p}", y, &y);
    // yは可変のため、変更できる。アドレスはそのまま。
    y = 6;
    println!("y = {}, yのアドレス: {:p}", y, &y);

    // ==========================================
    // 2. シャドーイング
    // ==========================================
    println!("\n--- 2. シャドーイング ---");
    let z = 5;
    println!("z = {}, zのアドレス: {:p}", z, &z);
    // letを重ねることで、同じ名前の変数を再定義（シャドーイング）できる。
    // mutと異なり、変更後も変数は不変であり、型を変更することもできる。
    let z = z + 1;
    println!("z = {}, zのアドレス: {:p}", z, &z);
    let z = z * 2;
    println!("z = {}, zのアドレス: {:p}", z, &z);
    // 型の変更も行える
    let z = "hello";
    println!("z = {}, zのアドレス: {:p}", z, &z);

    // ==========================================
    // 3. スコープとシャドーイング
    // ==========================================
    println!("\n--- 3. スコープとシャドーイング ---");
    let zz = 10;
    println!("外側 zz の値: {}, アドレス: {:p}", zz, &zz);
    {
        // シャドーイングにより、zzは再定義される。
        let zz = zz * 2;
        println!("内側 zz の値: {}, アドレス: {:p}", zz, &zz);
    }
    // {}のスコープを抜けると、内側のzzはドロップされ、外側のzzが再び参照される。
    println!("外側 zz の値: {}, アドレス: {:p}", zz, &zz);

    // ==========================================
    // 4. 定数（const）
    // ==========================================
    println!("\n--- 4. 定数（const） ---");
    const SECONDS_IN_A_DAY: u32 = 60 * 60 * 24;
    println!("1日あたりの秒数（定数）: {}", SECONDS_IN_A_DAY);
    {
        const SECONDS_IN_A_WEEK: u32 = 60 * 60 * 24 * 7;
        println!("1週間の秒数（定数）: {}", SECONDS_IN_A_WEEK);
    }
    println!("SECONDS_IN_A_WEEK を定義したスコープを抜けた");
    // constもスコープを抜けると、参照できなくなる。以下のコメントアウトを外すと、エラーが出る（E0425: cannot find value）。
    //  println!("1週間の秒数（定数）: {}", SECONDS_IN_A_WEEK);

    // ==========================================
    // 5. タプル
    // ==========================================
    println!("\n--- 5. タプル ---");
    // タプルは、異なる型をまとめられる。固定長。
    let tup: (&str, i32, bool) = ("Rust", 2024, true);
    // タプルは、各要素の型が異なるので、for文でループできない。
    // 各要素の型は異なるため、インデックスアクセスをする必要がある。
    println!("タプルの0番目の要素: {}", tup.0);
    println!("タプルの1番目の要素: {}", tup.1);
    println!("タプルの2番目の要素: {}", tup.2);
    println!("タプル全体: {:?}", tup);

    // 分割代入
    let (name, year, is_fun) = tup;
    println!("分割代入: {}, {}, {}", name, year, is_fun);

    // ==========================================
    // 6. 配列
    // ==========================================
    println!("\n--- 6. 配列 ---");
    // 配列は、同じ型をまとめられる。固定長。
    let arr: [i32; 3] = [10, 20, 30];
    println!("配列全体: {:?}", arr);
    // 要素へのアクセス
    println!("配列の0番目の要素: {}", arr[0]);
    // 配列はforループ可能
    for i in arr {
        println!("要素: {}", i);
    }
    // 分割代入
    let [arr0, arr1, arr2] = arr;
    println!("分割代入: {}, {}, {}", arr0, arr1, arr2);

    // ==========================================
    // 7. スライスとファットポインタ
    // ==========================================
    println!("\n--- 7. スライスとファットポインタ ---");

    // arrのインデックスが1番目以降の要素を参照する（インデックス3番目は含まない）
    let slice: &[i32] = &arr[1..3];
    println!("スライス: {:?}", slice);
    println!("スライスの長さ: {}", slice.len());
    println!("スライスの0番目の要素: {}", slice[0]);
    for i in slice {
        println!("スライスの要素: {}", i);
    }
    println!("スライスの先頭アドレス: {:?}", slice.as_ptr());
    println!("配列の先頭アドレス: {:?}", arr.as_ptr());
    println!("配列の1番目の要素のアドレス: {:p}", &arr[1]);

    // 通常の参照のサイズ（8バイト）
    println!(
        "通常の参照 (&i32) のサイズ: {} バイト",
        std::mem::size_of::<&i32>()
    );

    // スライス参照のサイズ（16バイト！）
    println!(
        "スライス参照 (&[i32]) のサイズ: {} バイト",
        std::mem::size_of::<&[i32]>()
    );
    println!(
        "変数 slice 自身のサイズ: {} バイト",
        std::mem::size_of_val(&slice)
    );

    // スライス（16バイト）を 2つの 64bit整数 (usize) として解釈する
    let ptr_and_len: (usize, usize) = unsafe { std::mem::transmute(slice) };

    println!(
        "ファットポインタの内部1 (先頭アドレス): 0x{:x}",
        ptr_and_len.0
    );
    println!("ファットポインタの内部2 (長さ len): {}", ptr_and_len.1);
}
